def get_homologous_species(gene_symbol):
    """
    Fetches homologous species for a given human gene symbol using the Ensembl REST API.
    """
    print(f"\n--- Starting Homology Search for {gene_symbol} ---")
    server = "https://rest.ensembl.org"
    ext = f"/homology/symbol/human/{gene_symbol}"

    try:
        response = requests.get(server + ext, headers=JSON_HEADERS)
        response.raise_for_status() # Raises an HTTPError for bad responses (4xx or 5xx)

        data = response.json()
        homology_list = data.get("data", [])[0].get("homologies", [])

        species_names = set()
        for homology in homology_list:
            target_species = homology.get("target", {}).get("species")
            if target_species and target_species != "homo_sapiens":
                species_names.add(target_species.replace('_', ' ').title())

        return sorted(list(species_names))
    except requests.exceptions.RequestException as e:
        print(f"API request failed during homology search: {e}")
        return []

def write_species_to_file(species_list, filename):
    """
    Writes a list of species names to a text file, one species per line.
    """
    try:
        with open(filename, 'w') as f:
            for species in species_list:
                f.write(f"{species}\n")
        print(f"-> Successfully wrote the list of homologous species to {filename}")
    except IOError as e:
        print(f"Error writing to homology file: {e}")


