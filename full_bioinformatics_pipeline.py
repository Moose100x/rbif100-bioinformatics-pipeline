    print(f"Writing {len(filtered_data)} sequences (length > 100) to {OUTPUT_FILENAME_FILTERED_TXT}...")
    with open(OUTPUT_FILENAME_FILTERED_TXT, 'w') as file:
        for seq_id, sequence in filtered_data.items():
            file.write(f"{seq_id}\t{sequence}\n")

    # 4d. Generate Summary Table
    generate_sequence_summary(OUTPUT_FILENAME_FILTERED_TXT, OUTPUT_FILENAME_SUMMARY_CSV)

    print("\n--- Pipeline Complete ---")
    print(f"FASTA sequence saved to: {OUTPUT_FILENAME_FASTA}")
    print(f"Homologous species list saved to: {OUTPUT_FILENAME_HOMOLOGY}")
    print(f"Sequence summary CSV saved to: {OUTPUT_FILENAME_SUMMARY_CSV}")
    print(f"Coding sequences saved to: {OUTPUT_FILENAME_CODING_FASTA}")


