def find_orfs(sequence, min_protein_length=5):
    """
    Finds Open Reading Frames (ORFs) in a DNA sequence across all 6 frames
    by translating and splitting the sequence by stop codons.
    """
    standard_table = CodonTable.unambiguous_dna_by_id[1]
    orfs = []
    
    # Loop through all 6 reading frames
    for frame in range(3):
        for strand in [1, -1]:
            # 1. Prepare sequence for current strand and frame
            current_seq = sequence
            strand_name = 'forward'
            if strand == -1:
                current_seq = sequence.reverse_complement()
                strand_name = 'reverse'
            
            # Sequence slice starts from the frame and goes to the end in steps of 3
            framed_nt_sequence = current_seq[frame:]
            
            # 2. Translate the entire frame, including stop codons
            # Use str() for sequence as BioPython is sometimes strict with Seq objects
            protein_seq = str(framed_nt_sequence.translate(table=standard_table, to_stop=False))
            
            # 3. Split the protein sequence by the stop codon ('*')
            protein_segments = protein_seq.split('*')
            
            # The start position of the ORF *in the framed sequence slice*
            current_aa_index = 0
            
            for prot in protein_segments:
                # 4. Check if the segment is long enough
                if len(prot) >= min_protein_length:
                    # ORF is found!
                    
                    # Nucleotide start in the current sequence (relative to 0 of the entire gene)
                    nt_start_in_frame = frame + (current_aa_index * 3)
                    nt_end_in_frame = nt_start_in_frame + (len(prot) * 3) + 3 # +3 for the stop codon
                    
                    orf_dna = current_seq[nt_start_in_frame : nt_end_in_frame]
                    
                    orfs.append((f"Frame {frame+1} ({strand_name})",
                                 nt_start_in_frame,
                                 nt_end_in_frame,
                                 prot, # Protein sequence (string)
                                 orf_dna,
                                 len(orf_dna)
                                ))
                                
                # Move the amino acid index past the segment and the *stop codon*
                # Length of prot + 1 (for the stop codon that was split out)
                current_aa_index += len(prot) + 1 
                
    return orfs
       
   
def identify_coding_sequences(fasta_file_path):
    """
    Reads a FASTA file, identifies coding sequences (ORFs), prints results,
    and returns the protein sequences as a list of SeqRecord objects.
    """
    orf_records = []  # To store SeqRecord objects for identified ORFs
    
    try:
        # Using SeqIO.parse for robustness
        for record in SeqIO.parse(fasta_file_path, "fasta"):
            print(f"Processing sequence for ORFs: {record.id}")
            orfs = find_orfs(record.seq)

            if orfs:
                print("Identified ORFs (sorted by length):")
                # Sort by protein length (index 3) in descending order
                orfs.sort(key=lambda x: len(x[3]), reverse=True)

                # Unpack the 6-element tuple (i is the ORF number index)
                for i, (frame_info, start, end, protein, nuc_seq, nt_length) in enumerate(orfs):

                    # 1. Terminal Printing
                    print(f"  - {frame_info}:")
                    print(f"    - Amino Acid Length: {len(protein)} aa")
                    print(f"    - Protein Sequence (start): {protein[:50]}...")

                    # 2. Create SeqRecord and Collect
                    # These variables (i, frame_info, protein) are now correctly in scope.
                    orf_id = f"{record.id}_ORF_{i+1}_{frame_info.replace(' ', '_')}"
                    orf_description = f"ORF from {record.id} in {frame_info} (Location: {start}-{end})"
                    
                    orf_record = SeqRecord(Seq(str(protein)), id=orf_id, description=orf_description)
                    orf_records.append(orf_record)

                print("-" * 30)
            else:
                print("No significant ORFs found.")
                print("-" * 30)

    except Exception as e:
        print(f"An error occurred during ORF identification: {e}", file=sys.stderr)
    
# This is the essential step for the main pipeline to access the data. 
    return orf_records

 
