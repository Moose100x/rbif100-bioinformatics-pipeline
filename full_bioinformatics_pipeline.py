def read_fasta(filename):
    """Reads a FASTA file and returns a dictionary of sequence IDs and strings."""
    sequencedict = {}
    sequencename = None

    try:
        with open(filename, 'r') as fasta_file:
            current_sequence = []
            for line in fasta_file:
                line = line.strip()
                if not line:
                    continue

                if line.startswith('>'):
                    # Save the previous sequence before starting a new one
                    if sequencename:
                        sequencedict[sequencename] = "".join(current_sequence)

                    # Start a new sequence
                    sequencename = line[1:].split()[0] # Use the first word as the key
                    current_sequence = []
                else:
                    # Append sequence lines
                    current_sequence.append(line)

            # Add the last sequence to the dictionary
            if sequencename:
                sequencedict[sequencename] = "".join(current_sequence)

    except FileNotFoundError:
        print(f"Error: The file '{filename}' was not found.")
        return None

    return sequencedict

def generate_sequence_summary(filtered_data_file, output_csv_file):
    """
    Generates a summary table (Pandas DataFrame) of filtered sequences,
    including sequence ID, length, and GC-content, and saves it to a CSV file.
    """
    print("\n--- Generating Sequence Summary (Phase 4) ---")
    summary_data = []

    with open(filtered_data_file, 'r') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue

            try:
                # Expects 'sequence_id\tsequence_string'
                seq_id, sequence = line.split('\t', 1)
            except ValueError:
                print(f"Skipping malformed line in filtered data file: {line}")
                continue

            seq_length = len(sequence)
            upper_sequence = sequence.upper()

            # Calculate GC-content
            gc_count = upper_sequence.count('G') + upper_sequence.count('C')
            gc_content = (gc_count / seq_length) * 100 if seq_length > 0 else 0

            summary_data.append({
                'Sequence ID': seq_id,
                'Length': seq_length,
                'GC-content (%)': round(gc_content, 2)
            })

    if summary_data:
        summary_df = pd.DataFrame(summary_data)
        summary_df.to_csv(output_csv_file, index=False)
        print(f"-> Summary table successfully saved to {output_csv_file}")
    else:
        print("-> No valid sequence data found to generate a summary.")


